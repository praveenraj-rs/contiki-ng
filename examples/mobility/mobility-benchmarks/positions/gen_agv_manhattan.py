#!/usr/bin/env python3
"""Generate a Cooja Mobility .dat trace for the "industrial AGV" scenario:
grid-constrained (ManhattanGrid-style) movement with frequent stop-and-go at
stations, speeds in the 0.5-2 m/s range, matching the requested use-case
criteria (aisles + pick/drop stops).

This is a small deterministic, reproducible stand-in for a real BonnMotion
ManhattanGrid run (tools/apps/bonnmotion-3.0.1 can generate a randomized one
the same way; see tools/apps/scripts/complete_mobility_setup.sh). Only the
AGV mote (index 3 = mote ID 4 in cooja-sims/cooja-agv.csc) moves; the root
and the two relay motes stay at their fixed positions.

Usage: python3 gen_agv_manhattan.py > agv_manhattan.dat
"""

import sys

# (x, y, dwell_seconds) waypoints - a rectangular aisle loop through the
# root/relay layout, pausing at each station like an AGV pick/drop stop.
STATIONS = [
    (-25.0, -30.0, 15.0),  # Station 1 (loading dock)
    (-25.0, 0.0, 10.0),    # Pass by Relay A (pick)
    (25.0, 0.0, 10.0),     # Pass by Relay B (drop)
    (25.0, 30.0, 15.0),    # Station 2 (loading dock)
]
# Speeds (m/s) for each leg between consecutive stations (and back again),
# within the 0.5-2 m/s "frequent stop-and-go" range.
SPEEDS_MS = [1.5, 2.0, 1.0, 1.5, 1.8, 0.8]

MOTE_INDEX = 3       # 0-based; AGV is the 4th mote
SAMPLE_PERIOD_S = 2  # waypoint density while moving


def lerp(a, b, t):
    return a + (b - a) * t


def emit_leg(t, x0, y0, x1, y1, speed):
    dist = ((x1 - x0) ** 2 + (y1 - y0) ** 2) ** 0.5
    duration = dist / speed if speed > 0 else 0.0
    steps = max(1, int(duration // SAMPLE_PERIOD_S))
    for i in range(1, steps + 1):
        frac = min(1.0, (i * SAMPLE_PERIOD_S) / duration) if duration > 0 else 1.0
        x = lerp(x0, x1, frac)
        y = lerp(y0, y1, frac)
        t += SAMPLE_PERIOD_S
        print(f"{MOTE_INDEX} {t:.3f} {x:.3f} {y:.3f}")
    return t + max(0.0, duration - steps * SAMPLE_PERIOD_S)


def main():
    print("# Cooja Mobility .dat file - industrial AGV (ManhattanGrid-style)")
    print("# Format: MoteIndex Time(s) X Y")
    print("# Generated by gen_agv_manhattan.py - grid-constrained, 0.5-2 m/s,")
    print("# frequent stop-and-go at stations (pick/drop dwell points).")
    x0, y0, dwell0 = STATIONS[0]
    t = 0.0
    print(f"{MOTE_INDEX} {t:.3f} {x0:.3f} {y0:.3f}")
    t += dwell0

    # Loop: forward through all stations, then back to the start - 6 legs
    # total, matching the 6 entries in SPEEDS_MS.
    route = STATIONS + list(reversed(STATIONS[:-1]))
    cur_x, cur_y = x0, y0
    for i in range(1, len(route)):
        nx, ny, dwell = route[i]
        speed = SPEEDS_MS[(i - 1) % len(SPEEDS_MS)]
        t = emit_leg(t, cur_x, cur_y, nx, ny, speed)
        cur_x, cur_y = nx, ny
        t += dwell

    sys.stderr.write(f"# total loop period: {t:.1f} s\n")


if __name__ == "__main__":
    main()
